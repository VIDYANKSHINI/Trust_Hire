import * as fs from "fs";
import * as path from "path";

async function main() {
  const artifactPath = path.join(
    __dirname,
    "../artifacts/contracts/TrustHire.sol/TrustHire.json"
  );
  if (!fs.existsSync(artifactPath)) {
    throw new Error("Artifact not found: " + artifactPath);
  }

  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  const abi = artifact.abi;

  const targetPath = path.join(__dirname, "../../web/lib/abi.ts");
  const content = `// Auto-generated by contracts/scripts/export-abi.ts
export const trustHireAbi = ${JSON.stringify(abi, null, 2)} as const;
`;

  fs.writeFileSync(targetPath, content, "utf8");
  console.log("ABI exported successfully to " + targetPath);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
